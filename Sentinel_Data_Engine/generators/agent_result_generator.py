"""
============================================================
Sentinel Data Engine

Agent Result Generator

Generates AI agent findings.
============================================================
"""

import random
from uuid import uuid4

from events.agent_result_event import AgentResultEvent


class AgentResultGenerator:

    AGENTS = {

        "VisionAgent": [

            "fire_detected",

            "smoke_detected",

            "ppe_violation",

            "NO_FINDING"

        ],

        "EquipmentAgent": [

            "equipment_fault",

            "bearing_failure",

            "overheating",

            "NO_FINDING"

        ],

        "EnvironmentAgent": [

            "gas_concentration_breach",

            "air_quality_warning",

            "NO_FINDING"

        ],

        "PermitAgent": [

            "permit_zone_overlap",

            "expired_permit",

            "NO_FINDING"

        ],

        "WorkerAgent": [

            "worker_fatigue",

            "worker_sos",

            "ppe_violation",

            "NO_FINDING"

        ]

    }

    def generate(

        self,

        site_id,

        zone_id,

        subject_ref

    ):

        agent = random.choice(

            list(self.AGENTS.keys())

        )

        finding = random.choice(

            self.AGENTS[agent]

        )

        confidence = round(

            random.uniform(

                0.75,

                0.99

            ),

            3

        )

        event = AgentResultEvent()

        event.site_id = site_id

        event.zone_id = zone_id

        event.partition_key = subject_ref

        event.metadata = {

            "simulation": True,

            "agent": agent

        }

        event.explanation = {

            "summary": finding,

            "confidence": {

                "value": confidence

            },

            "reasoning": [

                "Generated by simulation"

            ]

        }

        event.payload = {

            "agent_result_id": str(uuid4()),

            "agent_name": agent,

            "agent_version": "1.0.0",

            "subject_ref": subject_ref,

            "finding": finding,

            "confidence": confidence

        }

        return event